#!/usr/bin/env python3
"""Iberia copies of Lithuanian migrations written after the first install.

    python3 tools/make-update.py ../litprofit > db/iberia-update-2026-11.sql

Same rewrite as make-schema.py: public. -> iberia. (profiles stays shared),
auth.uid() -> iberia.admin_uid(). Lines touching the Lithuanian 'documents'
bucket are dropped -- Iberia has its own bucket.
"""
import re, sys, pathlib
LT = pathlib.Path(sys.argv[1]) / "db"
FILES = ["migrate-enquiries-5.sql", "migrate-enquiry-payments.sql", "migrate-enquiry-records.sql"]
out = ["-- Generated by tools/make-update.py from the litprofit repo. Do not edit.",
       "-- Enquiries: invoiced/paid/folder columns, payments in parts, document records.",
       "-- Safe to run more than once. Run in the SQL editor of LitProfit calculator.", ""]
for f in FILES:
    s = (LT / f).read_text()
    s = s.replace("public.profiles", "\x00P\x00").replace("public.", "iberia.").replace("\x00P\x00", "public.profiles")
    s = s.replace("auth.uid()", "iberia.admin_uid()")
    s = "\n".join(l for l in s.splitlines() if "storage.buckets" not in l)
    assert "public." not in s.replace("public.profiles", ""), f
    out += [f"-- ==== from {f}", s, ""]
out.append("notify pgrst, 'reload schema';")
print("\n".join(out))
